"""Ground truth: a toy 2D "molecule" made of a short chain plus one ligand.

AlphaFold 3 predicts the 3D structure of a complex (protein chains, nucleic
acids, ligands) from its sequence and chemistry. To make every tensor fit on a
screen we replace real proteins with a 2D lattice-free bead model whose
structures come from an explicit energy, so "the physics" is known exactly:

::

    tokens   i = 0 .. N_RES-1   chain residues, type H (sticky) or P (polar)
             i = N_RES          one ligand atom, type L, not bonded to the chain

    E(x) =  K_BOND  Σ_i (|x_{i+1} - x_i| - 1)^2                   bonds
          + K_BEND  Σ_i (1 - cos(φ_i - φ0(type_i)))               signed turns
          + K_REP   Σ_{|i-j|>=2} relu(D_REP - d_ij)^2             excluded volume
          - EPS_HH  Σ_{H,H, |i-j|>=3} g(d_ij - D_HH)              H-H contacts
          - EPS_L   Σ_{H} g(d_iL - D_L)                           ligand pocket

with ``g(u) = exp(-u^2 / (2 W^2))``. ``φ_i`` is the *signed* angle by which the
chain turns at residue ``i``. Because the preferred turn ``φ0`` is signed
(H turns left, P turns slightly right), the energy is **chiral**: a structure and
its mirror image have different energies, so a model can get the handedness
wrong, which is exactly one of AlphaFold 3's reported failure modes.

Several local minima exist for most sequences (which H residues touch, where the
ligand sits), so the "structure of a sequence" is a *distribution*. That is the
reason a diffusion model is the right tool and a regression head is not.

Structures are generated by annealed Langevin dynamics followed by gradient
descent, vectorised over many samples with ``jax.vmap``.
"""

from __future__ import annotations

from typing import NamedTuple

import jax
import jax.numpy as jnp
from jax import Array

H, P, L = 0, 1, 2
TYPE_NAMES = ("H", "P", "L")


class EnergyParams(NamedTuple):
    """Constants of the toy energy (lengths in bond units)."""

    k_bond: float = 100.0
    k_bend: float = 3.0
    phi_h: float = 1.2       # preferred turn at H (rad, ~ +69 deg, left)
    phi_p: float = -0.35     # preferred turn at P (rad, ~ -20 deg, right)
    k_rep: float = 60.0
    d_rep: float = 1.0
    eps_hh: float = 2.0
    d_hh: float = 1.15
    eps_l: float = 2.5
    d_l: float = 1.0
    width: float = 0.25


def _well(u: Array, w: float) -> Array:
    return jnp.exp(-(u**2) / (2 * w**2))


def signed_turns(x_chain: Array) -> Array:
    """Signed turning angle at each internal residue, shape ``(N_RES-2,)``."""
    b = x_chain[1:] - x_chain[:-1]
    cross = b[:-1, 0] * b[1:, 1] - b[:-1, 1] * b[1:, 0]
    dot = jnp.sum(b[:-1] * b[1:], axis=-1)
    return jnp.arctan2(cross, dot)


def energy_terms(x: Array, types: Array, p: EnergyParams = EnergyParams()) -> dict[str, Array]:
    """Every term of ``E`` for one structure ``x`` of shape ``(N, 2)``.

    ``types`` has shape ``(N,)``; the last token must be the ligand.
    """
    xc, xl = x[:-1], x[-1]
    tc = types[:-1]
    n = xc.shape[0]

    bond_len = jnp.linalg.norm(xc[1:] - xc[:-1], axis=-1)
    e_bond = p.k_bond * jnp.sum((bond_len - 1.0) ** 2)

    phi0 = jnp.where(tc[1:-1] == H, p.phi_h, p.phi_p)
    e_bend = p.k_bend * jnp.sum(1.0 - jnp.cos(signed_turns(xc) - phi0))

    d = jnp.linalg.norm(x[:, None] - x[None] + 1e-9, axis=-1)
    idx = jnp.arange(x.shape[0])
    sep = jnp.abs(idx[:, None] - idx[None])
    is_lig = (idx[:, None] == n) | (idx[None] == n)
    nonbonded = ((sep >= 2) | is_lig) & (idx[:, None] < idx[None])
    e_rep = p.k_rep * jnp.sum(jnp.where(nonbonded, jax.nn.relu(p.d_rep - d) ** 2, 0.0))

    hh = (tc[:, None] == H) & (tc[None] == H)
    sep_c = sep[:n, :n]
    upper = jnp.triu(jnp.ones((n, n), bool), k=3) & (sep_c >= 3)
    e_hh = -p.eps_hh * jnp.sum(jnp.where(hh & upper, _well(d[:n, :n] - p.d_hh, p.width), 0.0))

    dl = jnp.linalg.norm(xc - xl, axis=-1)
    e_lig = -p.eps_l * jnp.sum(jnp.where(tc == H, _well(dl - p.d_l, p.width), 0.0))

    return {"bond": e_bond, "bend": e_bend, "repulsion": e_rep, "H-H": e_hh, "ligand": e_lig}


def energy(x: Array, types: Array, p: EnergyParams = EnergyParams()) -> Array:
    return sum(energy_terms(x, types, p).values())


def random_sequence(key: Array, n_res: int, p_h: float = 0.5) -> Array:
    """Random H/P chain followed by one ligand token."""
    chain = jnp.where(jax.random.uniform(key, (n_res,)) < p_h, H, P)
    return jnp.concatenate([chain, jnp.array([L])]).astype(jnp.int32)


def random_start(key: Array, n_res: int) -> Array:
    """A random walk with unit steps for the chain, and a random ligand position."""
    k1, k2 = jax.random.split(key)
    ang = jnp.cumsum(jax.random.uniform(k1, (n_res - 1,), minval=-1.2, maxval=1.2))
    steps = jnp.stack([jnp.cos(ang), jnp.sin(ang)], -1)
    chain = jnp.concatenate([jnp.zeros((1, 2)), jnp.cumsum(steps, 0)])
    chain = chain - chain.mean(0)
    lig = jax.random.normal(k2, (1, 2)) * 1.0
    return jnp.concatenate([chain, lig])


def centre(x: Array) -> Array:
    """Subtract the centroid of all tokens (AF3 centres every structure too)."""
    return x - x.mean(0, keepdims=True)


def fold(key: Array, types: Array, n_anneal: int = 1500, n_quench: int = 500,
         dt: float = 2e-3, t_start: float = 1.5, p: EnergyParams = EnergyParams()) -> Array:
    """One ground-truth structure: annealed Langevin, then gradient descent."""
    n_res = types.shape[0] - 1
    k0, kl = jax.random.split(key)
    x = random_start(k0, n_res)
    grad = jax.grad(energy)

    def langevin(x, inp):
        k, temp = inp
        g = jnp.clip(grad(x, types, p), -200, 200)
        return x - dt * g + jnp.sqrt(2 * dt * temp) * jax.random.normal(k, x.shape), None

    temps = t_start * jnp.linspace(1.0, 0.0, n_anneal) ** 2
    x, _ = jax.lax.scan(langevin, x, (jax.random.split(kl, n_anneal), temps))

    def descend(x, _):
        return x - dt * jnp.clip(grad(x, types, p), -200, 200), None

    x, _ = jax.lax.scan(descend, x, None, length=n_quench)
    return centre(x)


fold_many = jax.jit(jax.vmap(fold, in_axes=(0, 0)))


def make_dataset(key: Array, n_sequences: int, samples_per_seq: int, n_res: int = 8) -> dict[str, Array]:
    """``n_sequences`` random sequences, each folded ``samples_per_seq`` times.

    Returns ``types (S, N)``, ``x (S, K, N, 2)`` and ``energy (S, K)``.
    """
    ks, kf = jax.random.split(key)
    types = jax.vmap(lambda k: random_sequence(k, n_res))(jax.random.split(ks, n_sequences))
    t_rep = jnp.repeat(types, samples_per_seq, axis=0)
    xs = fold_many(jax.random.split(kf, n_sequences * samples_per_seq), t_rep)
    e = jax.vmap(energy)(xs, t_rep)
    n = types.shape[1]
    return {
        "types": types,
        "x": xs.reshape(n_sequences, samples_per_seq, n, 2),
        "energy": e.reshape(n_sequences, samples_per_seq),
    }


def mirror(x: Array) -> Array:
    """Reflect across the y axis: same distances, opposite handedness."""
    return x * jnp.array([-1.0, 1.0])


def wrong_handed(x: Array, types: Array, p: EnergyParams = EnergyParams()) -> Array:
    """True if the mirror image fits the preferred turns better than ``x`` does."""
    e = energy_terms(x, types, p)["bend"]
    em = energy_terms(mirror(x), types, p)["bend"]
    return em < e


def bond_error(x: Array) -> Array:
    """Mean absolute deviation of chain bond lengths from 1."""
    xc = x[:-1]
    return jnp.mean(jnp.abs(jnp.linalg.norm(xc[1:] - xc[:-1], axis=-1) - 1.0))
